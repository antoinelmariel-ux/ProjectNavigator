const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const babel = require('@babel/core');

const ROOT_DIR = path.resolve(__dirname, '..');
const SRC_DIR = path.join(ROOT_DIR, 'src');
const OUTPUT_FILE = path.join(SRC_DIR, 'module-manifest.js');
const DEFERRED_OUTPUT_FILE = path.join(SRC_DIR, 'module-manifest.deferred.js');

// Jumeaux « données » des deux manifests : même contenu, extension .txt. Sous http(s),
// index.html les charge en priorité. Sur un site SharePoint dont l'autorisation « custom
// script » a expiré, un .txt reste remplaçable alors qu'un .js ne l'est plus : mettre à jour
// l'app ne demande donc plus de réécrire un fichier script.
// Voir docs/migration-v2/DEPLOIEMENT-MISE-A-JOUR-SANS-CUSTOM-SCRIPT.md
const CORE_PAYLOAD_FILE = path.join(SRC_DIR, 'module-manifest.core.txt');
const DEFERRED_PAYLOAD_FILE = path.join(SRC_DIR, 'module-manifest.deferred.txt');
const VERSION_PAYLOAD_FILE = path.join(SRC_DIR, 'module-manifest.version.txt');
const STYLESHEET_FILE = path.join(SRC_DIR, 'styles', 'tailwind-internal.css');

// Gros composants hors du premier rendu : chargés dans un manifest différé
// (après le premier paint) pour alléger le chemin critique.
const DEFERRED_MODULES = new Set([
  'src/components/BackOffice.jsx',
  'src/components/ProjectShowcase.jsx',
  'src/components/SynthesisReport.jsx'
]);

const ALLOWED_EXTENSIONS = new Set(['.js', '.jsx', '.json']);
const EXCLUDED_SEGMENTS = ['vendor'];
// module-loader.js et module-manifest.js sont chargés directement par index.html,
// pas via le ModuleLoader : on les exclut du manifest.
const EXCLUDED_FILES = ['module-manifest.js', 'module-manifest.deferred.js', 'module-loader.js'];

// Même configuration que l'ancien runtime Babel : conversion ES modules -> CommonJS,
// JSX -> React.createElement, et on laisse async/await en natif (navigateurs modernes).
const BABEL_OPTIONS = {
  babelrc: false,
  configFile: false,
  sourceType: 'module',
  presets: [
    [
      '@babel/preset-env',
      {
        modules: 'commonjs',
        exclude: ['transform-regenerator', 'transform-async-to-generator']
      }
    ],
    '@babel/preset-react'
  ]
};

const isAllowedFile = (filePath) => ALLOWED_EXTENSIONS.has(path.extname(filePath).toLowerCase());

const isExcluded = (filePath) =>
  EXCLUDED_SEGMENTS.some((segment) => filePath.split(path.sep).includes(segment));

const listFiles = (dir) => {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  return entries.flatMap((entry) => {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      return listFiles(fullPath);
    }
    if (
      entry.isFile() &&
      isAllowedFile(fullPath) &&
      !isExcluded(fullPath) &&
      !EXCLUDED_FILES.includes(entry.name)
    ) {
      return [fullPath];
    }
    return [];
  });
};

const toRelativeWebPath = (filePath) => path.relative(ROOT_DIR, filePath).split(path.sep).join('/');

const buildManifest = () => {
  const files = listFiles(SRC_DIR);
  const manifest = {};

  files.forEach((filePath) => {
    const relativePath = toRelativeWebPath(filePath);
    const source = fs.readFileSync(filePath, 'utf8');
    const extension = path.extname(filePath).toLowerCase();

    if (extension === '.json') {
      // Les modules JSON sont interprétés par le ModuleLoader : on garde le brut.
      manifest[relativePath] = source;
      return;
    }

    const { code } = babel.transform(source, { ...BABEL_OPTIONS, filename: filePath });
    manifest[relativePath] = code;
  });

  return manifest;
};

const splitManifest = (manifest) => {
  const core = {};
  const deferred = {};
  Object.entries(manifest).forEach(([key, value]) => {
    if (DEFERRED_MODULES.has(key)) {
      deferred[key] = value;
    } else {
      core[key] = value;
    }
  });
  return { core, deferred };
};

// La feuille Tailwind générée voyage dans le payload : sans elle, une mise à jour qui
// introduit une nouvelle classe s'afficherait sans style tant que le .css — non remplaçable
// dans le même scénario que le .js — n'est pas réécrit.
const readStylesheet = () => {
  try {
    return fs.readFileSync(STYLESHEET_FILE, 'utf8');
  } catch {
    console.warn(
      `Feuille de styles introuvable (${STYLESHEET_FILE}) : payload publié sans styles. Lancez « npm run generate:css ».`
    );
    return '';
  }
};

// Empreinte déterministe du triplet publié : elle sert à la fois de clé de cache et de
// marqueur d'intégrité côté navigateur (les trois fichiers doivent annoncer la même version,
// sinon le payload est rejeté au profit des manifests embarqués).
const computeVersion = (core, deferred, styles) =>
  crypto
    .createHash('sha256')
    .update(JSON.stringify(core))
    .update(JSON.stringify(deferred))
    .update(styles)
    .digest('hex')
    .slice(0, 16);

const writeCoreManifest = (core, version) => {
  const banner = '/* Auto-generated by scripts/generate-module-manifest.js — code déjà transpilé (Babel build). */';
  const content =
    `${banner}\n` +
    `window.__COMPLIANCE_NAVIGATOR_MANIFEST__ = ${JSON.stringify(core, null, 2)};\n` +
    `window.__CN_MANIFEST_BUNDLED_VERSION__ = ${JSON.stringify(version)};\n`;
  fs.writeFileSync(OUTPUT_FILE, content, 'utf8');
};

const writeDeferredManifest = (deferred, version) => {
  const banner = '/* Auto-generated by scripts/generate-module-manifest.js — modules différés (hors premier rendu). */';
  // Ce fichier est figé au dernier déploiement de scripts, alors que le payload .txt peut
  // être plus récent. Le garde évite qu'il ne réinjecte ses modules périmés par-dessus ceux
  // du payload : un mélange de versions qui ne casserait que le back-office, la vitrine et la
  // synthèse, au premier clic, longtemps après le démarrage.
  const content =
    `${banner}\n` +
    'if (!window.__CN_MANIFEST_FROM_PAYLOAD__) {\n' +
    '  window.__COMPLIANCE_NAVIGATOR_MANIFEST__ = window.__COMPLIANCE_NAVIGATOR_MANIFEST__ || {};\n' +
    `  Object.assign(window.__COMPLIANCE_NAVIGATOR_MANIFEST__, ${JSON.stringify(deferred, null, 2)});\n` +
    `  window.__CN_MANIFEST_BUNDLED_DEFERRED_VERSION__ = ${JSON.stringify(version)};\n` +
    '  window.__CN_DEFERRED_READY__ = true;\n' +
    "  try { window.dispatchEvent(new Event('cn:manifest-deferred-ready')); } catch (error) { /* no-op */ }\n" +
    '}\n';
  fs.writeFileSync(DEFERRED_OUTPUT_FILE, content, 'utf8');
};

const writePayloads = (core, deferred, styles, version) => {
  fs.writeFileSync(
    CORE_PAYLOAD_FILE,
    JSON.stringify({ kind: 'core', version, styles, modules: core }),
    'utf8'
  );
  fs.writeFileSync(
    DEFERRED_PAYLOAD_FILE,
    JSON.stringify({ kind: 'deferred', version, modules: deferred }),
    'utf8'
  );
  fs.writeFileSync(VERSION_PAYLOAD_FILE, `${JSON.stringify({ version }, null, 2)}\n`, 'utf8');
};

const manifest = buildManifest();
const { core, deferred } = splitManifest(manifest);
const styles = readStylesheet();
const version = computeVersion(core, deferred, styles);

writeCoreManifest(core, version);
writeDeferredManifest(deferred, version);
writePayloads(core, deferred, styles, version);

console.log(
  `Manifest transpilé (version ${version}) : ${Object.keys(core).length} entrées cœur → ${OUTPUT_FILE}\n` +
    `                     ${Object.keys(deferred).length} entrées différées → ${DEFERRED_OUTPUT_FILE}\n` +
    `                     payloads .txt → ${CORE_PAYLOAD_FILE}\n` +
    `                                     ${DEFERRED_PAYLOAD_FILE}\n` +
    `                                     ${VERSION_PAYLOAD_FILE}`
);
